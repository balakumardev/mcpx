import type { ToolInfo } from '../types.js';
import { jsonSchemaToType, schemaRequiresArgs } from './json-schema-types.js';
import { escapeJsDoc, quoteProp } from './utils.js';

/** The tools of one registered server. */
export interface ServerTools {
  server: string;
  tools: ToolInfo[];
}

const SERVER_INDENT = '  ';
const TOOL_INDENT = '    ';

function jsDoc(tool: ToolInfo, indent: string): string[] {
  const text = (tool.description?.trim() || tool.title?.trim() || '').replace(/\r\n?/g, '\n');
  const lines = text ? text.split('\n').map((line) => escapeJsDoc(line).trimEnd()) : [];
  if (tool.annotations?.readOnlyHint === true) {
    if (lines.length > 0) lines.push('');
    lines.push('@readonly');
  }
  if (lines.length === 0) return [];
  return [`${indent}/**`, ...lines.map((line) => (line ? `${indent} * ${line}` : `${indent} *`)), `${indent} */`];
}

function toolDeclaration(tool: ToolInfo, indent: string): string[] {
  const doc = jsDoc(tool, indent);
  const name = quoteProp(tool.name);
  try {
    const input = jsonSchemaToType(tool.inputSchema, indent);
    const optional = schemaRequiresArgs(tool.inputSchema) ? '' : '?';
    const output = tool.outputSchema ? jsonSchemaToType(tool.outputSchema, indent) : 'unknown';
    return [...doc, `${indent}${name}(args${optional}: ${input}): Promise<${output}>;`];
  } catch {
    // One malformed schema must not take the whole declaration file down.
    return [...doc, `${indent}${name}(args?: unknown): Promise<unknown>;`];
  }
}

/**
 * One `.d.ts` declaring `mcp`: `mcp["<server>"].<tool>(args)` resolves to the
 * tool's output (its outputSchema type, else `unknown`). Server and tool names
 * are used verbatim as keys and quoted only when they are not valid identifiers,
 * so distinct names can never collide.
 */
export function generateMcpTypes(servers: ServerTools[]): string {
  const header = '// Generated by `mcpkit types`. Inside `mcpkit exec`, call tools as mcp["<server>"].<tool>(args).';
  if (servers.length === 0) return `${header}\ndeclare const mcp: {};\n`;

  const lines: string[] = [header, 'declare const mcp: {'];
  for (const { server, tools } of servers) {
    if (tools.length === 0) {
      lines.push(`${SERVER_INDENT}${quoteProp(server)}: {};`);
      continue;
    }
    lines.push(`${SERVER_INDENT}${quoteProp(server)}: {`);
    for (const tool of tools) lines.push(...toolDeclaration(tool, TOOL_INDENT));
    lines.push(`${SERVER_INDENT}};`);
  }
  lines.push('};');
  return `${lines.join('\n')}\n`;
}
