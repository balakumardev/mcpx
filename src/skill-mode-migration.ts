/**
 * Moving an agent from per-server skills to the guide: find the skills mcpkit generated, copy them
 * to a backup, then remove them. Everything that is not provably a generated per-server skill is
 * left alone: the `mcpkit-cli` guide, a skill somebody wrote by hand under a name of the same
 * shape, a directory with anything else in it, a symlink. So is a generated skill that is also the
 * live skill of another agent on per-server skills: one file that both read.
 */

/** The guide's directory: it is written by `writeMetaSkill`, never removed here. */
const GUIDE_DIR = `${SKILL_DIR_PREFIX}cli`;

/** The two lines every generated per-server skill opens its body with (both formats, every version since they were added). */
const NOT_NATIVE_LINE = /^> \*\*Important:\*\* These are NOT native MCP tools\. Do NOT call them as `mcp__.+__\*` tools\.$/;
const CALL_LINE = /^> All tools must be invoked via Bash using `mcpkit call .+ <tool_name> '<json_params>'`\.$/;

/** A generated skill is some kilobytes; anything beyond this is not read at all. */
const MAX_SKILL_BYTES = 32 * 1024 * 1024;

/**
 * Whether `content` is a per-server skill as the generators write it: the frontmatter names the
 * directory it sits in (`name: mcpkit-<server>`, bare or in quotes) and the body, not the
 * frontmatter, carries the two "NOT native MCP tools / invoke via mcpkit call" lines. Skills from an
 * mcpkit older than those lines do not match, and so are never removed.
 */
export function isGeneratedSkillContent(content: string, dirName: string): boolean {
  const lines = content.split('\n');
  if (lines[0] !== '---') return false;
  const close = lines.indexOf('---', 1);
  if (close === -1) return false;

  const nameLine = lines.slice(1, close).find((line) => line.startsWith('name:'));
  if (nameLine === undefined) return false;
  let name = nameLine.slice('name:'.length).trim();
  if (name.startsWith('"')) {
    try {
      name = JSON.parse(name) as string;
    } catch {
      return false;
    }
  }
  if (name !== dirName) return false;

  const body = lines.slice(close + 1);
  return body.some((line) => NOT_NATIVE_LINE.test(line)) && body.some((line) => CALL_LINE.test(line));
}

/** The global skills directory of `agent`, taken from its generator (as the guide's path is). */
export async function skillsRootOf(agent: AgentType): Promise<string> {
  const generate = await getGenerator(agent);
  const { filePath } = generate({
    serverName: 'cli',
    tools: [],
    transport: { type: 'stdio', command: 'mcpkit', args: [] },
    scope: 'global',
  });
  return dirname(dirname(filePath));
}

export interface AgentMigrationPlan {
  agent: AgentType;
  root: string;
  guidePath: string;
  /** Absolute skill directories that were generated by mcpkit and are to be removed. */
  remove: string[];
  /** Skill-shaped directories that stay, with why. */
  keep: Array<{
    dir: string;
    reason: string;
    /** The agent on per-server skills that reads the same file, when that alone keeps it: it can go once nobody does. */
    sharedWith?: AgentType;
  }>;
}

type Verdict = { generated: true } | { generated: false; reason: string };

/** Whether `dir` is a plain directory holding only a regular SKILL.md that mcpkit generated. */
async function inspectSkillDir(dir: string): Promise<Verdict> {
  const dirName = basename(dir);
  const notOurs = (reason: string): Verdict => ({ generated: false, reason });
  let entries: string[];
  try {
    entries = await readdir(dir);
  } catch (err) {
    return notOurs(`it cannot be read (${(err as Error).message})`);
  }
  if (!entries.includes('SKILL.md')) return notOurs('it has no SKILL.md');
  if (entries.length > 1) return notOurs('it holds files besides SKILL.md');

  const file = join(dir, 'SKILL.md');
  const info = await lstat(file);
  if (!info.isFile()) return notOurs('its SKILL.md is not a regular file');
  if (info.size > MAX_SKILL_BYTES) return notOurs('its SKILL.md is too large to be one of ours');
  return isGeneratedSkillContent(await readFile(file, 'utf-8'), dirName)
    ? { generated: true }
    : notOurs('it was not written by mcpkit: its SKILL.md lacks the generated header');
}

/**
 * The servers an agent on per-server skills has a skill for, or `'every'` when the registry cannot be
 * read: then nobody can tell its live skills from its leftovers, so all of them count as live.
 */
export type OwnedServers = ReadonlySet<string> | 'every';

/**
 * The servers each agent on per-server skills has a skill for (`servers` with the agents each is
 * installed for, or undefined when the registry cannot be read): what moving another agent to the
 * guide must leave where the two read one file (see `planGuideMigration`).
 */
export function perServerSkillOwners(
  settings: LoadedSettings,
  servers: ReadonlyArray<{ entry: ServerEntry; agents: AgentType[] }> | undefined,
  env: NodeJS.ProcessEnv = process.env,
): Map<AgentType, OwnedServers> {
  const owners = new Map<AgentType, OwnedServers>();
  for (const agent of ALL_AGENTS) {
    if (resolveSkillModeSource(settings, agent, env).mode !== 'per-server') continue;
    // No registry, no way to know which servers it has: it keeps them all (fails closed).
    owners.set(agent, servers === undefined ? 'every' : new Set(servers.filter((server) => server.agents.includes(agent)).map((server) => server.entry.name)));
  }
  return owners;
}

/**
 * The agent of `owners`, other than `agent`, whose per-server skill of the server of `dir` is the
 * very file `dir` holds, or undefined when there is none. A symlink at any level makes that so: the
 * skills directory (`~/.codex/skills -> ~/.claude/skills`), the skill folder, or the SKILL.md.
 */
async function sharerOf(agent: AgentType, dir: string, owners: ReadonlyMap<AgentType, OwnedServers>): Promise<AgentType | undefined> {
  const name = basename(dir);
  const server = name.slice(SKILL_DIR_PREFIX.length);
  const skills: Array<{ agent: AgentType; filePath: string }> = [];
  for (const [other, servers] of owners) {
    if (other === agent || (servers !== 'every' && !servers.has(server))) continue;
    skills.push({ agent: other, filePath: join(await skillsRootOf(other), name, 'SKILL.md') });
  }
  return skills.length === 0 ? undefined : (await sameFileAs(join(dir, 'SKILL.md'), skills))?.agent;
}

/**
 * What moving `agent` to the guide would do, decided from what is on disk; writes nothing. A
 * generated skill stays when it is the same file as the skill of its server of another agent of
 * `owners` (from `perServerSkillOwners`): removing it would remove that agent's skill too.
 */
export async function planGuideMigration(agent: AgentType, owners: ReadonlyMap<AgentType, OwnedServers> = new Map()): Promise<AgentMigrationPlan> {
  const root = await skillsRootOf(agent);
  const plan: AgentMigrationPlan = { agent, root, guidePath: join(root, GUIDE_DIR, 'SKILL.md'), remove: [], keep: [] };

  let names: string[];
  try {
    names = (await readdir(root, { withFileTypes: true }))
      .filter((entry) => entry.isDirectory() || entry.isSymbolicLink())
      .map((entry) => entry.name);
  } catch (err) {
    if ((err as NodeJS.ErrnoException).code === 'ENOENT' || (err as NodeJS.ErrnoException).code === 'ENOTDIR') return plan;
    throw err;
  }

  for (const name of names.sort()) {
    if (name === GUIDE_DIR || !isSkillDirName(name)) continue;
    const dir = join(root, name);
    if ((await lstat(dir)).isSymbolicLink()) {
      plan.keep.push({ dir, reason: 'it is a symlink' });
      continue;
    }
    const verdict = await inspectSkillDir(dir);
    // A file another agent still reads as its skill goes from that agent too, so it stays; `sharedWith` lets the reconcile come back to it.
    const owner = verdict.generated ? await sharerOf(agent, dir, owners) : undefined;
    if (owner !== undefined) plan.keep.push({ dir, reason: `it is the same file as the per-server skill of ${owner}`, sharedWith: owner });
    else if (verdict.generated) plan.remove.push(dir);
    else plan.keep.push({ dir, reason: verdict.reason });
  }
  return plan;
}

/** The directory every backup goes under. */
export function backupRootPath(): string {
  return join(homedir(), '.mcpkit', 'skill-backups');
}

const MAX_BACKUP_SUFFIX = 100;

/** Create `dir` (and its missing parents) owner-only: each directory this creates is set to exactly 0700 (the umask may only narrow a mode). */
async function makePrivateDirectory(dir: string): Promise<void> {
  const first = await mkdir(dir, { recursive: true, mode: 0o700 });
  if (first === undefined) return;
  for (let current = dir; ; current = dirname(current)) {
    await chmod(current, 0o700);
    if (current === first) return;
  }
}

/** Copy one skill directory (a single SKILL.md) into `target`, byte for byte, owner-only. */
async function copySkillDirectory(source: string, target: string): Promise<void> {
  const bytes = await readFile(join(source, 'SKILL.md'));
  await makePrivateDirectory(target);
  const file = join(target, 'SKILL.md');
  const handle = await open(file, 'wx', 0o600);
  try {
    await handle.writeFile(bytes);
    // The creation mode is cut by the umask, which may only narrow it; this makes it exact.
    await handle.chmod(0o600);
  } finally {
    await handle.close();
  }
}

/**
 * Copy every directory the plans would remove to `~/.mcpkit/skill-backups/<yyyymmddhhmmss>/<agent>/<dir>/`
 * (directories 0700, files 0600). Returns that timestamped directory, or undefined when there is
 * nothing to copy. A second backup in the same second gets `-1`, `-2`, ... and never overwrites one.
 * Throws at the first failure and removes the partial backup; nothing has been removed from the
 * skills directories at that point, because this only reads them.
 */
export async function backupSkillDirs(plans: AgentMigrationPlan[], now: Date = new Date()): Promise<string | undefined> {
  const copies = plans.flatMap((plan) => plan.remove.map((dir) => ({ agent: plan.agent, dir })));
  if (copies.length === 0) return undefined;

  const parent = backupRootPath();
  await makePrivateDirectory(parent);
  let backup: string | undefined;
  for (let attempt = 0; backup === undefined && attempt <= MAX_BACKUP_SUFFIX; attempt++) {
    const candidate = join(parent, `${timestamp(now)}${attempt === 0 ? '' : `-${attempt}`}`);
    try {
      await mkdir(candidate, { mode: 0o700 });
      await chmod(candidate, 0o700);
      backup = candidate;
    } catch (err) {
      if ((err as NodeJS.ErrnoException).code !== 'EEXIST') throw err;
    }
  }
  if (backup === undefined) throw new Error(`could not pick a backup directory under ${parent}: ${MAX_BACKUP_SUFFIX} backups were made in the same second`);

  try {
    for (const { agent, dir } of copies) await copySkillDirectory(dir, join(backup, agent, basename(dir)));
  } catch (err) {
    await rm(backup, { recursive: true, force: true });
    throw err;
  }
  return backup;
}

/**
 * Remove the planned directories, and return the ones that went. Each one is checked again right
 * before it goes, and is kept when it is no longer a generated skill (somebody rewrote it since the
 * plan), and each is removed through `removeSkillDirectory`, which refuses a path that is not
 * `<skills dir>/mcpkit-<server>/SKILL.md`.
 */
export async function removeGeneratedSkillDirs(plans: AgentMigrationPlan[]): Promise<string[]> {
  const removed: string[] = [];
  for (const plan of plans) {
    for (const dir of plan.remove) {
      if (dirname(dir) !== plan.root) {
        throw new Error(`Refusing to remove ${dir}: it is not directly inside ${plan.root}.`);
      }
      if (!(await inspectSkillDir(dir)).generated) continue;
      await removeSkillDirectory(join(dir, 'SKILL.md'));
      removed.push(dir);
    }
  }
  return removed;
}
